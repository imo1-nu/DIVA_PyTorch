"""Materialize pinned source revisions with identical execution-only adapters."""
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[2]
CONDITIONS = {
    'author': '9170932e9d77a6bcfb2c00e05df362660d11b3e0',
    'corrected': '2920c35503711a9faa4780e3a34ed6d74adcd65b',
}


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def materialize(directory, condition):
    revision = CONDITIONS[condition]
    destination = Path(directory).resolve()/'sources'/condition
    destination.mkdir(parents=True, exist_ok=True)
    archive = subprocess.check_output(['git', '-C', str(ROOT), 'archive', '--format=tar', revision, 'src'])
    with tarfile.open(fileobj=io.BytesIO(archive)) as source:
        source.extractall(destination, filter='data')
    src = destination/'src'
    patches = []

    def replace(filename, before, after, count):
        path = src/filename
        text = path.read_text()
        if text.count(before) != count:
            raise ValueError(f'Unexpected source for {condition}: {filename}: {before!r}')
        path.write_text(text.replace(before, after))
        patches.append(dict(file=filename, before=before, after=after, occurrences=count))

    # Keep the original zero buffer for short targets and support the 2 s
    # target generated by the author's own extractor. Same adapter in both.
    replace('diva_cerebellum.py', 'torch.zeros(101)', 'torch.zeros(max(101, num_steps))', 1)
    replace('diva_targets.py', "                x0 = base_x0  # + wrapper\n",
            "                x0 = base_x0  # + wrapper\n"
            "                x1 = production_info[min_label]\n"
            "                x2 = production_info[max_label]\n", 1)
    # CPU geometry avoids forced CUDA transfers inside the NumPy-based
    # synthesis path. No F0, noise, period, or interpolation formulas change.
    replace('diva_vocaltract.py', "torch.device('cuda:0')", "torch.device('cpu')", 2)
    replace('diva_vocaltract.py', '.cuda()', '.cpu()', 3)
    files = {str(path.relative_to(src)): sha256(path)
             for path in sorted(src.rglob('*')) if path.is_file()}
    fingerprint = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
    provenance = dict(condition=condition, revision=revision, adapters=patches,
                      source_files_sha256=files, source_fingerprint=fingerprint)
    (destination/'provenance.json').write_text(json.dumps(provenance, indent=2)+'\n')
    return provenance
